set -eu

usage()
{
	printf '%s\n' "usage: $0 <output-vmlinux.h>" >&2
	exit 2
}

if [ "$#" -ne 1 ]; then
	usage
fi

out=$1
repo=$(CDPATH= cd "$(dirname "$0")/../.." && pwd)
uapi=$repo/third_party/bpf-next/tools/include/uapi/linux/bpf.h

if [ ! -r "$uapi" ]; then
	printf '%s\n' "shirudo: missing bpf-next UAPI header: $uapi" >&2
	printf '%s\n' "         initialize third_party/bpf-next first" >&2
	exit 1
fi
if ! grep -q '[[:space:]]signature_size;' "$uapi"; then
	printf '%s\n' "shirudo: bpf-next UAPI header lacks bpf_attr.signature_size" >&2
	exit 1
fi

mkdir -p "$(dirname "$out")"
cat > "$out" <<'EOF'
/* SPDX-License-Identifier: (BSD-2-Clause OR GPL-2.0) */
/*
 * AUTO-GENERATED by packaging/bpf/gen-vmlinux-h.sh. Do not commit.
 *
 * Minimal CO-RE vmlinux.h fallback for reproducible package builds.
 * GitHub-hosted runners can expose older host kernel BTF than shirudo's
 * target UAPI, so package builds use this generated header instead of
 * /sys/kernel/btf/vmlinux.
 */

#ifndef SHIRUDO_PACKAGE_VMLINUX_H
#define SHIRUDO_PACKAGE_VMLINUX_H

#ifndef BPF_NO_PRESERVE_ACCESS_INDEX
#pragma clang attribute push(__attribute__((preserve_access_index)), \
			     apply_to = record)
#endif

#include <stdbool.h>
#include <linux/bpf.h>

struct mnt_idmap;

struct super_block {
	__u32 s_dev;
};

struct inode {
	unsigned long i_ino;
	struct super_block *i_sb;
};

struct dentry {
	struct inode *d_inode;
};

struct file {
	unsigned int f_mode;
	struct inode *f_inode;
};

struct mm_struct {
	struct file *exe_file;
};

struct task_struct {
	struct mm_struct *mm;
};

#ifndef BPF_NO_PRESERVE_ACCESS_INDEX
#pragma clang attribute pop
#endif

#endif /* SHIRUDO_PACKAGE_VMLINUX_H */
EOF

printf 'shirudo: wrote %s\n' "$out"
