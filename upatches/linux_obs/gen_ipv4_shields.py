#!/usr/bin/env python3
"""Generate the signed build-time IPv4 shield trie header."""

from __future__ import annotations

import argparse
import ipaddress
from pathlib import Path


# ipv4_shields is a 4096-page arena and each node is 520 bytes. Keep the
# generated node count within the arena's addressable capacity, including
# the state header.
MAX_NODES = (4096 * 4096 - 8) // 520


def read_networks(path: Path) -> list[ipaddress.IPv4Network]:
	result: set[ipaddress.IPv4Network] = set()
	if not path.exists():
		return []
	for line_number, raw in enumerate(path.read_text().splitlines(), 1):
		text = raw.split("#", 1)[0].strip()
		if not text:
			continue
		try:
			if ":" in text:
				raise ValueError("IPv6 is not supported")
			network = ipaddress.ip_network(text, strict=False)
		except ValueError as error:
			raise ValueError(f"{path}:{line_number}: {error}") from error
		if not isinstance(network, ipaddress.IPv4Network):
			raise ValueError(f"{path}:{line_number}: IPv4 network required")
		result.add(network)
	return sorted(result, key=lambda network: (int(network.network_address), network.prefixlen))


def build_trie(networks: list[ipaddress.IPv4Network]) -> list[dict[str, object]]:
	nodes: list[dict[str, object]] = [{"children": [0] * 256, "terminal": False}]

	def new_node() -> int:
		if len(nodes) >= MAX_NODES:
			raise ValueError(f"generated trie exceeds {MAX_NODES} nodes")
		nodes.append({"children": [0] * 256, "terminal": False})
		return len(nodes) - 1

	def ensure_child(node_index: int, octet: int) -> int:
		children = nodes[node_index]["children"]
		assert isinstance(children, list)
		child = children[octet]
		if child == 0:
			child_index = new_node()
			children[octet] = child_index + 1
			return child_index
		return int(child) - 1

	for network in networks:
		address = int(network.network_address)
		full_octets, partial_bits = divmod(network.prefixlen, 8)
		node_index = 0
		for depth in range(full_octets):
			octet = (address >> (24 - depth * 8)) & 0xFF
			node_index = ensure_child(node_index, octet)

		if partial_bits == 0:
			nodes[node_index]["terminal"] = True
			continue

		# Expand the final partial stride into all matching byte values.
		# This keeps lookup verifier-friendly: every trie edge consumes
		# exactly one complete byte.
		octet = (address >> (24 - full_octets * 8)) & 0xFF
		base = octet & (0xFF << (8 - partial_bits))
		for suffix in range(1 << (8 - partial_bits)):
			leaf = ensure_child(node_index, base + suffix)
			nodes[leaf]["terminal"] = True

	return nodes


def render(input_path: Path, networks: list[ipaddress.IPv4Network],
		   nodes: list[dict[str, object]]) -> str:
	lines = [
		"/* Generated by gen_ipv4_shields.py; do not edit manually. */",
		f"/* Source: {input_path.name}; rules: {len(networks)}. */",
		"#ifndef IPV4_SHIELDS_GENERATED_H",
		"#define IPV4_SHIELDS_GENERATED_H",
		f"#define IPV4_SHIELDS_NODE_COUNT {len(nodes)}u",
		"",
	]
	lines.extend([
		"#define IPV4_SHIELDS_COPY_NODES(state) do { \\",
	])
	for node_index, node in enumerate(nodes):
		children = node["children"]
		assert isinstance(children, list)
		for child_index, child in enumerate(children):
			if child:
				lines.append(
					f"\t(state)->nodes[{node_index}].child[{child_index}] = {int(child)}u; \\")
		if node["terminal"]:
			lines.append(f"\t(state)->nodes[{node_index}].terminal = 1; \\")
	lines.extend(["} while (0)", "", "#endif"])
	return "\n".join(lines) + "\n"


def main() -> int:
	parser = argparse.ArgumentParser()
	parser.add_argument("input", type=Path)
	parser.add_argument("output", type=Path)
	parser.add_argument("--check", action="store_true")
	args = parser.parse_args()

	networks = read_networks(args.input)
	content = render(args.input, networks, build_trie(networks))
	if args.check:
		return int(not args.output.exists() or args.output.read_text() != content)
	args.output.write_text(content)
	return 0


if __name__ == "__main__":
	try:
		raise SystemExit(main())
	except ValueError as error:
		print(f"gen_ipv4_shields.py: {error}")
		raise SystemExit(2)
